@router.post("/plans/auto", status_code=201)
def auto_schedule(
    body: S.AutoScheduleIn,
    request: Request,
    current: User = Depends(require_perm("production:schedule:auto")),
    db: Session = Depends(get_db),
):
    """自动排期（规则式贪心）：按设备 / 人员 / 样车时段冲突 + 物料可用量生成方案。"""
    base = body.base_date or date.today()
    tasks = svc.pick_tasks(
        db,
        task_ids=body.task_ids or None,
        project_id=body.project_id,
        date_from=body.date_from,
        date_to=body.date_to,
    )
    if not tasks:
        raise BizException(R.PRODUCTION_NO_TASK_TO_SCHEDULE, "没有符合条件的待排任务")
    name = body.name or f"{base:%Y-%m-%d} 自动排期"
    plan, rows = svc.generate_plan(db, tasks, name, base, current)
    for row in rows:
        row.plan_no_text = plan.plan_no
    db.flush()
    audit(
        db, user_id=current.id, module="production", action="plan_auto_schedule",
        biz_type="prod_plan", biz_id=plan.id,
        detail={"planNo": plan.plan_no, "tasks": len(tasks), "rows": len(rows), "conflict": plan.conflict_count},
        trace_id=getattr(request.state, "trace_id", ""),
    )
    db.commit()
    data = _plan_out(plan, len(rows))
    data["schedules"] = [_schedule_out(r) for r in rows]
    return data


@router.post("/plans/{pid}/publish")
def publish_plan(
    pid: int,
    request: Request,
    current: User = Depends(require_perm("production:schedule:publish")),
    db: Session = Depends(get_db),
):
    """发布方案：二次校验资源时段冲突，通过后占用资源并回写任务排期。"""
    plan = _load_plan(db, pid)
    if plan.status not in ("draft", "published"):
        raise BizException(R.PRODUCTION_INVALID_STATE, "当前方案状态不允许发布")
    rows = list(
        db.scalars(
            select(ProdSchedule)
            .where(ProdSchedule.plan_id == pid, ProdSchedule.deleted == 0)
            .order_by(ProdSchedule.seq, ProdSchedule.id)
        ).all()
    )
    if not rows:
        raise BizException(R.PRODUCTION_INVALID_STATE, "方案内没有排程行")
    others = list(
        db.scalars(
            select(ProdSchedule).where(
                ProdSchedule.deleted == 0,
                ProdSchedule.status.in_(("published", "confirmed")),
                ProdSchedule.plan_id != pid,
            )
        ).all()
    )
    problems = svc.detect_conflicts(rows + others)
    if problems:
        raise BizException(R.PRODUCTION_SCHEDULE_CONFLICT, "；".join(problems[:5]))
    now = datetime.now()
    for row in rows:
        if row.status == "conflict":
            continue
        row.status = "published"
        row.source = row.source or "auto"
    plan.status = "published"
    plan.published_at = now
    plan.published_by_name = current.name or ""
    svc.write_back_task_dates(db, rows)
    audit(
        db, user_id=current.id, module="production", action="plan_publish",
        biz_type="prod_plan", biz_id=plan.id, detail={"planNo": plan.plan_no, "rows": len(rows)},
        trace_id=getattr(request.state, "trace_id", ""),
    )
    db.commit()
    data = _plan_out(plan, len(rows))
    data["schedules"] = [_schedule_out(r) for r in rows]
    return data


@router.post("/plans/{pid}/cancel")
def cancel_plan(
    pid: int,
    request: Request,
    current: User = Depends(require_perm("production:schedule:publish")),
    db: Session = Depends(get_db),
):
    plan = _load_plan(db, pid)
    if plan.status == "confirmed":
        raise BizException(R.PRODUCTION_INVALID_STATE, "已确认的方案不可取消")
    plan.status = "cancelled"
    rows = db.scalars(select(ProdSchedule).where(ProdSchedule.plan_id == pid, ProdSchedule.deleted == 0)).all()
    for row in rows:
        if row.status in ("scheduled", "published"):
            row.status = "cancelled"
    audit(
        db, user_id=current.id, module="production", action="plan_cancel",
        biz_type="prod_plan", biz_id=plan.id, detail={"planNo": plan.plan_no},
        trace_id=getattr(request.state, "trace_id", ""),
    )
    db.commit()
    return _plan_out(plan, len(rows))


