@router.put("/schedules/{sid}")
def update_schedule(
    sid: int,
    body: S.ScheduleIn,
    request: Request,
    current: User = Depends(require_perm("production:schedule:edit")),
    db: Session = Depends(get_db),
):
    """人工调整排程行（资源 / 时间 / 数量）。调整后置 source=manual。"""
    row = _load_schedule(db, sid)
    if row.status == "confirmed":
        raise BizException(R.PRODUCTION_INVALID_STATE, "已确认的排程行不可修改")
    if body.version is not None and body.version != row.version:
        raise BizException(R.GENERIC_OPTIMISTIC_LOCK)
    if body.resource_type:
        row.resource_type = body.resource_type
    if body.resource_id is not None:
        row.resource_id = body.resource_id
    if body.resource_code:
        row.resource_code = body.resource_code
    if body.resource_name:
        row.resource_name = body.resource_name
    if body.quantity:
        row.quantity = body.quantity
    if body.unit:
        row.unit = body.unit
    if body.plan_start:
        row.plan_start = body.plan_start
    if body.plan_end:
        row.plan_end = body.plan_end
    if body.plan_start and body.plan_end and body.plan_end <= body.plan_start:
        raise BizException(R.GENERIC_PARAM, "计划结束时间必须晚于开始时间")
    if body.status:
        row.status = body.status
    if body.remark:
        row.remark = body.remark
    row.source = "manual"
    row.conflict_reason = ""
    if row.plan_start and row.plan_end:
        row.duration_hours = round((row.plan_end - row.plan_start).total_seconds() / 3600, 2)
    db.flush()
    audit(
        db, user_id=current.id, module="production", action="schedule_update",
        biz_type="prod_schedule", biz_id=row.id, detail={"scheduleNo": row.schedule_no},
        trace_id=getattr(request.state, "trace_id", ""),
    )
    db.commit()
    return _schedule_out(row)


