def _t(v) -> str:
    if isinstance(v, datetime):
        return v.strftime("%Y-%m-%d %H:%M:%S")
    return v or ""


def _d(v) -> str:
    if isinstance(v, date):
        return v.strftime("%Y-%m-%d")
    return v or ""


def _text(mapping: dict[str, str], value: str | None) -> str:
    key = value or ""
    return mapping.get(key, key)


def _plan_out(p: ProdPlan, schedule_count: int = 0) -> dict:
    return {
        "id": p.id,
        "planNo": p.plan_no,
        "name": p.name,
        "planDate": _d(p.plan_date),
        "status": p.status,
        "statusText": _text(PLAN_STATUS_CN, p.status),
        "autoGenerated": bool(p.auto_generated),
        "taskCount": p.task_count,
        "conflictCount": p.conflict_count,
        "scheduleCount": schedule_count or p.task_count,
        "generatedByName": p.generated_by_name,
        "publishedAt": _t(p.published_at),
        "remark": p.remark,
        "version": p.version,
        "createTime": _t(p.create_time),
        "updateTime": _t(p.update_time),
    }


