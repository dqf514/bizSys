@router.get("/resources/occupancy")
def resource_occupancy(
    request: Request,
    user: User = Depends(require_perm("production:schedule:list")),
    db: Session = Depends(get_db),
):
    """资源占用视图：按资源维度汇总已占用的时段（设备 / 人员 / 样车 / 物料）。"""
    resource_type = request.query_params.get("resourceType")
    stmt = select(ProdSchedule).where(
        ProdSchedule.deleted == 0,
        ProdSchedule.status.in_(("published", "confirmed")),
    )
    if resource_type:
        stmt = stmt.where(ProdSchedule.resource_type == resource_type)
    rows = list(db.scalars(stmt.order_by(ProdSchedule.resource_type, ProdSchedule.plan_start)).all())
    grouped: dict[tuple[str, str], dict] = {}
    for r in rows:
        key = (r.resource_type, r.resource_name or r.resource_code or str(r.resource_id))
        entry = grouped.setdefault(
            key,
            {
                "resourceType": r.resource_type,
                "resourceTypeText": _text(RESOURCE_CN, r.resource_type),
                "resourceId": r.resource_id,
                "resourceName": r.resource_name,
                "resourceCode": r.resource_code,
                "occupiedHours": 0.0,
                "taskCount": 0,
                "windows": [],
            },
        )
        hours = (r.plan_end - r.plan_start).total_seconds() / 3600 if r.plan_start and r.plan_end else 0
        entry["occupiedHours"] = round(entry["occupiedHours"] + hours, 2)
        entry["taskCount"] += 1
        entry["windows"].append(
            {
                "scheduleId": r.id,
                "scheduleNo": r.schedule_no,
                "taskId": r.task_id,
                "taskNo": r.task_no,
                "taskName": r.task_name,
                "planStart": _t(r.plan_start),
                "planEnd": _t(r.plan_end),
                "status": r.status,
                "statusText": _text(SCHEDULE_STATUS_CN, r.status),
            }
        )
    return {"items": list(grouped.values()), "total": len(grouped)}


